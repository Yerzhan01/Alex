import os
import json
from openai import OpenAI

# the newest OpenAI model is "gpt-4o" which was released May 13, 2024.
# do not change this unless explicitly requested by the user
OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY")
openai = OpenAI(api_key=OPENAI_API_KEY)

def generate_health_report(user_data, report_type='free'):
    """
    Generate personalized health report using OpenAI GPT-4o
    report_type: 'free' for short report, 'full' for detailed report
    """
    
    if report_type == 'free':
        prompt = create_free_report_prompt(user_data)
    else:
        prompt = create_full_report_prompt(user_data)
    
    try:
        response = openai.chat.completions.create(
            model="gpt-4o",
            messages=[
                {
                    "role": "system",
                    "content": "Ты — ИИ-коуч по здоровью по имени Алекс, говорящий на русском языке, с характером заботливого, прямолинейного старшего брата. Твоя задача — создать персонализированный отчет о здоровье."
                },
                {
                    "role": "user", 
                    "content": prompt
                }
            ],
            temperature=0.7,
            max_tokens=4000 if report_type == 'full' else 1500
        )
        
        return response.choices[0].message.content
        
    except Exception as e:
        print(f"Error generating report: {e}")
        return "Извините, произошла ошибка при генерации отчета. Попробуйте позже."

def create_free_report_prompt(user_data):
    """Create prompt for free short report"""
    return f"""
Создай КРАТКИЙ персонализированный отчет о здоровье (максимум 800 слов) для пользователя со следующими данными:

{json.dumps(user_data, ensure_ascii=False, indent=2)}

Структура краткого отчета:
1. 🧠 **Краткая оценка состояния** (2-3 предложения)
2. ⚠️ **Главные риски** (3-4 пункта)
3. 💪 **Топ-5 рекомендаций** (конкретные действия)
4. 🎯 **Первый шаг сегодня** (одно простое действие)

Пиши в стиле заботливого старшего брата: дерзко, но с заботой. Используй эмоджи и простые слова.
Если пользователь мусульманин - упомяни связь духовного и физического здоровья.
"""

