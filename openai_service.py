# the newest OpenAI model is "gpt-4o" which was released May 13, 2024.
# do not change this unless explicitly requested by the user
OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY")

# Initialize OpenAI client only if API key is available
openai = None
if OPENAI_API_KEY:
    try:
        from openai import OpenAI
        openai = OpenAI(api_key=OPENAI_API_KEY)
    except ImportError:
        print("OpenAI library not available")
    except Exception as e:
        print(f"Error initializing OpenAI: {e}")

def generate_health_report(user_data, report_type='free'):
    """
    Generate personalized health report using OpenAI GPT-4o
    report_type: 'free' for short report, 'full' for detailed report
    """
    
    # Check if OpenAI is available
    if not openai:
        return get_demo_report(user_data, report_type)
    
    if report_type == 'free':
        prompt = create_free_report_prompt(user_data)
    else:
        prompt = create_full_report_prompt(user_data)
    
    try:
        response = openai.chat.completions.create(
            model="gpt-4o",
            messages=[
                {
                    "role": "system",
                    "content": "Ты — ИИ-коуч по здоровью по имени Алекс, говорящий на русском языке, с характером заботливого, прямолинейного старшего брата. Твоя задача — создать персонализированный отчет о здоровье."
                },
                {
                    "role": "user", 
                    "content": prompt
                }
            ],
            temperature=0.7,
            max_tokens=4000 if report_type == 'full' else 1500
        )
        
        return response.choices[0].message.content
        
    except Exception as e:
        print(f"Error generating report: {e}")
        return get_demo_report(user_data, report_type)

